#!/usr/bin/env node
/**
 * @file scripts/collect-metrics.mjs
 * @description Build docs/metrics.md, the single source of truth for
 * CodeForge quality metrics, from machine-readable test output.
 *
 * Inputs (each optional; missing ones are reported as "not collected"):
 *   backend/coverage/coverage-summary.json    (vitest --coverage, json-summary)
 *   backend/test-results.json                 (vitest --reporter=json)
 *   frontend/coverage/coverage-summary.json
 *   frontend/test-results.json
 *   .playwright-results/results.json          (Playwright JSON reporter)
 *   docs/metrics-lighthouse.json                      (manual Lighthouse record)
 *
 * Usage:
 *   node scripts/collect-metrics.mjs              write docs/metrics.md
 *   node scripts/collect-metrics.mjs --stdout     print the Markdown only
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function readJson(relativePath) {
    const file = join(root, relativePath);

    if (!existsSync(file)) {
        return null;
    }

    return JSON.parse(readFileSync(file, 'utf8'));
}

function coverageRow(label, summary) {
    if (!summary) {
        return `| ${label} | not collected | | | |`;
    }

    const { statements, branches, functions, lines } = summary.total;
    const pct = (metric) => `${metric.pct.toFixed(2)}%`;

    return `| ${label} | ${pct(statements)} | ${pct(branches)} | ${pct(functions)} | ${pct(lines)} |`;
}

function vitestRow(label, results) {
    if (!results) {
        return `| ${label} | not collected | |`;
    }

    const status = results.numFailedTests === 0 ? 'pass' : 'FAIL';

    return `| ${label} | ${results.numPassedTests}/${results.numTotalTests} | ${status} |`;
}

function playwrightRow(results) {
    if (!results) {
        return '| Playwright E2E | not collected | |';
    }

    const { expected = 0, unexpected = 0, flaky = 0, skipped = 0 } = results.stats ?? {};
    const total = expected + unexpected + flaky + skipped;
    const status = unexpected === 0 ? (flaky ? `pass (${flaky} flaky)` : 'pass') : 'FAIL';

    return `| Playwright E2E | ${expected + flaky}/${total} | ${status} |`;
}

function lighthouseSection(record) {
    if (!record) {
        return 'No Lighthouse record. Run Lighthouse and update `docs/metrics-lighthouse.json`.';
    }

    const rows = Object.entries(record.scores)
        .map(([name, values]) => `| ${name} | ${values.desktop ?? '—'} | ${values.mobile ?? '—'} |`)
        .join('\n');

    return [
        `Recorded manually on ${record.date} against ${record.url} (${record.tool}).`,
        'Lighthouse is not run in CI; update `docs/metrics-lighthouse.json` after each audit.',
        '',
        '| Metric | Desktop | Mobile |',
        '|---|---:|---:|',
        rows,
    ].join('\n');
}

export function buildMetricsMarkdown(inputs, generatedAt = new Date()) {
    return `# CodeForge Quality Metrics

> Generated by \`scripts/collect-metrics.mjs\` on ${generatedAt.toISOString().slice(0, 10)}.
> This file is the single source of truth for test and coverage numbers;
> other documents link here instead of repeating them. CI regenerates it
> on every run and publishes it in the job summary.

## Tests

| Suite | Passed | Status |
|---|---:|---|
${vitestRow('Backend (Vitest)', inputs.backendTests)}
${vitestRow('Frontend unit + rendering (Vitest)', inputs.frontendTests)}
${playwrightRow(inputs.e2e)}

## Coverage

| Package | Statements | Branches | Functions | Lines |
|---|---:|---:|---:|---:|
${coverageRow('Backend', inputs.backendCoverage)}
${coverageRow('Frontend', inputs.frontendCoverage)}

Enforced thresholds: backend 85/80/85/85, frontend 90/90/90/90
(statements/branches/functions/lines). Builds fail below them.

## Lighthouse

${lighthouseSection(inputs.lighthouse)}
`;
}

export function collectInputs() {
    return {
        backendTests: readJson('backend/test-results.json'),
        frontendTests: readJson('frontend/test-results.json'),
        backendCoverage: readJson('backend/coverage/coverage-summary.json'),
        frontendCoverage: readJson('frontend/coverage/coverage-summary.json'),
        e2e: readJson('.playwright-results/results.json'),
        lighthouse: readJson('docs/metrics-lighthouse.json'),
    };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const markdown = buildMetricsMarkdown(collectInputs());

    if (process.argv.includes('--stdout')) {
        process.stdout.write(markdown);
    } else {
        writeFileSync(join(root, 'docs/metrics.md'), markdown);
        console.log('Wrote docs/metrics.md');
    }
}
